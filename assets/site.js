/* ================= HERO DOT WAVE ================= */
const cv=document.getElementById('wave');
if(cv){
  const ctx=cv.getContext('2d'),reduce=matchMedia('(prefers-reduced-motion: reduce)').matches;
  let W,H,t=0,raf,visible=true;
  const size=()=>{const d=Math.min(devicePixelRatio||1,2);W=cv.clientWidth;H=cv.clientHeight;cv.width=W*d;cv.height=H*d;ctx.setTransform(d,0,0,d,0,0);};
  const frame=()=>{
    ctx.clearRect(0,0,W,H);
    const cols=W<700?60:110,rows=34,f=W*0.9,hz=H*0.4;
    for(let r=0;r<rows;r++){const z=1+r*0.14;
      for(let c=0;c<cols;c++){const x=(c/(cols-1)-0.5)*7;
        const y=Math.sin(x*0.9+t)*0.32+Math.cos(z*1.3-t*0.8)*0.28+Math.sin((x+z)*0.6+t*0.5)*0.22;
        const sx=W*0.62+(x*f)/(z*3.2),sy=hz+((1.15-y)*f*0.5)/(z*3.2)+H*0.1;
        if(sx<-10||sx>W+10||sy<0||sy>H)continue;
        const a=Math.max(0,1-r/rows)*(0.35+0.65*((y+0.8)/1.6)),s=Math.max(0.6,2.4/z);
        ctx.fillStyle=y>0.2?`rgba(11,168,159,${(a*0.9).toFixed(3)})`:`rgba(11,168,159,${(a*0.35).toFixed(3)})`;
        ctx.fillRect(sx,sy,s,s);}}
  };
  const loop=()=>{t+=0.012;frame();if(visible)raf=requestAnimationFrame(loop);};
  size();frame();addEventListener('resize',()=>{size();frame();});
  if(!reduce)new IntersectionObserver(es=>{visible=es[0].isIntersecting;cancelAnimationFrame(raf);if(visible)loop();}).observe(cv);
}


def crumbs(root, trail):
    items = [f'<li><a href="{root}index.html">Home</a></li>']
    for t,h in trail: items.append(f'<li><a href="{root}{h}">{e(t)}</a></li>' if h else f'<li aria-current="page">{e(t)}</li>')
    return f'<nav aria-label="Breadcrumb"><ol class="crumbs">{"".join(items)}</ol></nav>'

def crumbs_ld(trail):
    items = [('Home','index.html')] + trail
    return {"@context":"https://schema.org","@type":"BreadcrumbList","itemListElement":[
        {"@type":"ListItem","position":i+1,"name":t,"item":SITE_URL+(h or '')} for i,(t,h) in enumerate(items) if h is not None]}


# 404 is served from any URL depth on GitHub Pages, so it must use absolute links.
def fix_404():
    f = OUT/'404.html'; s = f.read_text(encoding='utf-8')
    base = SITE_URL.split('github.io',1)[1] if 'github.io' in SITE_URL else '/'
    s = s.replace('data-root=""', f'data-root="{base}"').replace('href="index.html"', f'href="{base}index.html"')
    import re
    s = re.sub(r'(href|src)="(?!https?:|#|/|data:)', lambda m: f'{m.group(1)}="{base}', s)
    f.write_text(s, encoding='utf-8')

def build_sitemap():
    urls = ''.join(f'<url><loc>{SITE_URL}{"" if p=="index.html" else p}</loc><lastmod>{date.today().isoformat()}</lastmod></url>' for p in PAGES if p!='404.html')
    (OUT/'sitemap.xml').write_text(f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{urls}</urlset>\n', encoding='utf-8')
    (OUT/'robots.txt').write_text(f'User-agent: *\nAllow: /\nDisallow: /_build/\nSitemap: {SITE_URL}sitemap.xml\n', encoding='utf-8')

